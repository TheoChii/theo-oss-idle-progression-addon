import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const code=await readFile(new URL('./progression-toolkit.addon.js',import.meta.url),'utf8');
assert(code.includes('v0.4.6'));
const mod=await import('data:text/javascript;base64,'+Buffer.from(code+'\nexport {warmGear,warmRange,warmup,warmPlan,restedMinutes,data};').toString('base64'));
const {warmGear,warmRange,warmup,warmPlan,restedMinutes}=mod;
const almost=(a,b,description)=>assert(Math.abs(a-b)<1e-7,description+': '+a+' vs '+b);
almost(warmGear(0),0,'zero gear');
almost(warmGear(10),10,'ten gear');
assert(warmGear(11)===11 && warmGear(12)<12,'diminishing returns from the second post-ladder gear');
almost(warmRange(0).peakStart,90,'zero gear peak threshold');
almost(warmRange(10).peakStart,45,'ten gear peak threshold');
almost(warmRange(10).peakEnd,120,'ten gear peak end');
for(const [mins,upgrades,expected] of [[0,0,0],[90,0,1],[300,0,.5],[360,0,0],[420,0,0],[45,10,1],[120,10,1],[330,10,.5],[390,10,0]])almost(warmup(mins,upgrades),expected,'official warmup '+mins+' / '+upgrades);
assert(warmup(121,10)<1,'after full warm peak declines');
const ideal=warmPlan(0,0,4,40,0);
assert.equal(ideal.kind,'play');assert.equal(ideal.plays,23);
almost(ideal.minutes,90,'optimal nonstop strain minutes');
almost(ideal.last,2,'short final map to hit narrow zero-gear peak');
const boosted=warmPlan(0,10,4,40,0);
assert.equal(boosted.kind,'play');assert.equal(boosted.plays,12);almost(boosted.minutes,45,'ten stamina upgrades cut target in half');
const moderate=warmPlan(0,0,4,20,0);
assert(moderate.minutes>ideal.minutes,'20% physical strain should warm slower');
assert.equal(warmPlan(0,0,4,10,0).kind,'impossible','low strain does not build warmup');
assert(warmPlan(0,10,4,40,.5).minutes>boosted.minutes,'breaks cost time');
assert.equal(warmPlan(90,0,4,40,0).kind,'ready','already warm');
const excessive=warmPlan(340,0,4,40,0);
assert.equal(excessive.kind,'cooldown');almost(excessive.minutes,625,'recovery after passing peak');
assert.equal(warmPlan(0,10,4,40,1).kind,'play');
const handlers={},content={innerHTML:''};
globalThis.localStorage={getItem:()=>JSON.stringify({fatigueMinutes:0,restMinutes:0,staminaUpgrades:10,warmPhysicalShare:40,warmMapMinutes:4,warmGapMinutes:0}),setItem(){}};
globalThis.window=new EventTarget();
globalThis.document={getElementById:()=>null,createElement:()=>({shadowRoot:null,dataset:{},classList:{contains(){return false},toggle(){}},attachShadow(){this.shadowRoot={innerHTML:'',addEventListener(event,cb){handlers[event]=cb},querySelector(selector){return selector==='#contents'?content:{classList:{add(){},toggle(){}}}},querySelectorAll(){return []}};return this.shadowRoot},remove(){}}),body:{appendChild(){}}};
mod.mount();
handlers.click({target:{closest:()=>({dataset:{tab:'Warm-up'},classList:{contains(){return false}}})},stopPropagation(){}});
const html=content.innerHTML;
assert(html.includes('Warm-up Planner'),'tab is rendered');
assert(html.includes('Full strain, no gaps'),'plan comparison shown');
assert(html.includes('Theoretical fastest'),'fastest plan card shown');
assert(html.includes('Stamina upgrades'),'Stamina upgrade count editable');
assert(html.includes('45 min'),'expected ten-gear ideal');
assert(html.includes('Warm-up does not directly affect XP'),'no promise of XP multiplier');
mod.unmount();
console.log('PASS: official warm-up curves, stamina gear, fastest route, overshoot recovery, strategy comparison and UI');
