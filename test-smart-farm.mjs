import assert from 'node:assert/strict';
import {optimizeFarm,findTargets,prestigeReady,fatigueKeep,mindblockKeep,PHYSICAL,BLOCKED} from './src/optimizer.js';
const approx=(a,b)=>assert(Math.abs(a-b)<1e-7, a+' != '+b);
approx(fatigueKeep(0),1);approx(fatigueKeep(300),1);approx(fatigueKeep(420),.05);
approx(mindblockKeep(0),1);approx(mindblockKeep(25),.25);
assert(prestigeReady({level:100,prestige:0}));assert(!prestigeReady({level:100,prestige:1}));
assert.deepEqual(findTargets({speed:{level:100,prestige:0},accuracy:{level:50,prestige:0}},'speed','accuracy',0).skills,['accuracy']);
assert.equal(findTargets({},'speed','accuracy',420,.1).target,'accuracy');
assert(PHYSICAL.has('coordination'),'1.2.5.0 classifies Coordination as physical');
assert(!BLOCKED.has('coordination'),'Coordination is no longer Mindblocked');
assert.equal(findTargets({},'coordination','reading',420,.1).target,'reading');
const coord={setId:9,beatmapId:99,rate:1,durationSec:60,failRate:0,mod:'NM',xp:{coordination:1000}};
const coordFresh=optimizeFarm({results:[coord],focus:'coordination',recent:new Map([[99,25]]),slots:1,fatigueMinutes:0});
assert.equal(coordFresh.rotation[0].expectedXp,1000,'Coordination repetitions are Mindblock-exempt');
const coordTired=optimizeFarm({results:[coord],focus:'coordination',recent:new Map([[99,25]]),slots:1,fatigueMinutes:400,cutoff:.01});
assert(coordTired.rotation[0].expectedXp<1000,'physical fatigue applies to Coordination');

assert.equal(findTargets({},'speed','stop',420,.1).skills.length,0);
const a={setId:1,beatmapId:10,rate:1,durationSec:60,failRate:0,xp:{speed:2000,accuracy:100,reading:50}};
const b={setId:2,beatmapId:11,rate:1.5,durationSec:60,failRate:0,xp:{speed:200,accuracy:1400,reading:800}};
const c={setId:3,beatmapId:12,rate:1.2,durationSec:35,failRate:0,xp:{speed:1200,accuracy:300,reading:500}};
const d={setId:1,beatmapId:10,rate:2,durationSec:35,failRate:0,xp:{speed:800,accuracy:100,reading:40}};
const input={results:[a,b,c,d],recent:new Map(),states:{},focus:'speed',backup:'accuracy',medals:1,slots:3,overheadSec:8,physicalShare:.4,minEfficiency:.3};
const fresh=optimizeFarm({...input,fatigueMinutes:0});
assert.equal(fresh.rotation[0].beatmapId,10,'fresh physical picks best XP/min');
assert.equal(fresh.rotation[0].rate,1,'best available rate selected');
const tired=optimizeFarm({...input,fatigueMinutes:420});
assert.equal(tired.rotation[0].beatmapId,11,'tired switches to accuracy');
assert.equal(tired.lastTarget,'accuracy');
assert(tired.switched);
const blocked=optimizeFarm({...input,focus:'accuracy',recent:new Map([[11,25]])});
assert.equal(blocked.rotation[0].beatmapId,12,'mindblocked map falls below another');
const tempo=optimizeFarm({...input,focus:'speed',recent:new Map([[10,0],[11,0],[12,0]])});
assert.equal(new Set(tempo.rotation.map(x=>x.beatmapId)).size,tempo.rotation.length,'no repeated difficulty even at different rates');
const ready=optimizeFarm({...input,focus:'speed',backup:'accuracy',states:{speed:{level:102,prestige:1}}});
assert.equal(ready.lastTarget,'accuracy','prestige-ready focus is skipped');
const stop=optimizeFarm({...input,focus:'speed',backup:'stop',states:{speed:{level:101,prestige:1}}});
assert.equal(stop.rotation.length,0,'stop targeting prestige-ready skill');
const total=optimizeFarm({...input,focus:'all',states:{speed:{level:101,prestige:1}}});
assert(total.rotation.length>0,'all mode keeps other non-ready skills');
assert(total.rotation[0].expectedXp>0);
const eliminated=optimizeFarm({...input,focus:'speed',slots:50,minEfficiency:1});
assert(eliminated.rotation.length<50,'do not pad managed queue with inefficient maps');
const fails=optimizeFarm({...input,results:[{...a,failRate:1}]});
assert.equal(fails.rotation.length,0,'failed maps excluded');
const hr={...b,mod:'HR',xp:{speed:200,accuracy:1540,reading:800}};
const nm={...b,mod:'NM'};
const hrResults=[{...a,mod:'NM'},{...c,mod:'NM'},nm,hr];
const hrStrategy=optimizeFarm({...input,results:hrResults,mod:'HR',focus:'accuracy',slots:1});
const nmStrategy=optimizeFarm({...input,results:hrResults,mod:'NM',focus:'accuracy',slots:1});
assert.equal(hrStrategy.mod,'HR');
assert.equal(hrStrategy.rotation[0].mod,'HR');
assert(hrStrategy.expectedPerMinute>nmStrategy.expectedPerMinute,'HR should be faster on a chart where accuracy bonus outweighs difficulty');
const difficultHR=optimizeFarm({...input,results:[{...b,mod:'HR',xp:{speed:100,accuracy:120,reading:0}},{...b,mod:'NM'}],mod:'HR',focus:'accuracy',slots:1});
assert(difficultHR.expectedPerMinute<nmStrategy.expectedPerMinute,'No Mod is superior where HR windows reduce accuracy XP');
const oneMore={...c,mod:'HR',rate:1.3,xp:{speed:100,accuracy:500,reading:500}};
const rateChoice=optimizeFarm({...input,results:[hr,oneMore],mod:'HR',focus:'accuracy',slots:2,minEfficiency:0.1});
assert(rateChoice.rotation.every(x=>x.mod==='HR'),'a playable rotation has exactly one mod');
const r=await import('node:fs/promises');
const source=await r.readFile('./src/smartFarm.js','utf8');
assert(source.includes("const LABEL='Theo Smart Farm (managed)'"));
assert(source.includes("this.consent=false"));
assert(source.includes("this.socketCharacterId!==Number(this.character?.id)"));
assert(source.includes("type:'queue:set'"));
assert(source.includes("asNumber(this.s.cutoff,1,100,10)"));
console.log('PASS: fatigue, mindblock, rate/HR strategy comparison, prestige stop, single-mod rotation and opt-in guards');
