import assert from 'node:assert/strict';
import {makePolicies,checkUpgrade,configExport,configImport,MAX_TIERS} from './src/autoUpgradeRules.js';
const keys=['speed','accuracy','memory'];
const defaults={goal:'xp',focus:'speed',slots:10,scanInterval:20,autoPlaylist:false,liveQueue:false};
const fresh=makePolicies(keys);
assert(keys.every(k=>!fresh[k].enabled&&fresh[k].targets.length===MAX_TIERS&&fresh[k].targets.every(n=>n===0)));
const purchase=({level,xp,upgrades,overdrive,prestige})=>{
 if(level<(upgrades+1)*10||upgrades>=10+prestige)throw Error('Not purchasable');
 const overspent=level-(upgrades+1)*10;
 return {level:level-10,xp,upgrades:upgrades+1,overdrive:overdrive+overspent/2,prestige};
};
let rule={enabled:true,targets:Array(30).fill(0)};
rule.targets[0]=10;
let test=checkUpgrade({level:19,xp:0,upgrades:0,prestige:0,overdrive:2},rule,purchase);
assert.equal(test.eligible,false);
assert.equal(test.preview.overdrive,6.5);
test=checkUpgrade({level:26,xp:0,upgrades:0,prestige:0,overdrive:2},rule,purchase);
assert.equal(test.eligible,true);
assert.equal(test.target,10);
assert.equal(test.gained,8);
rule.targets[1]=30;
test=checkUpgrade({level:36,xp:0,upgrades:1,prestige:0,overdrive:18},rule,purchase);
assert.equal(test.eligible,false,'stage two must have separate target');
assert.equal(test.target,30);
assert.equal(checkUpgrade({level:40,xp:0,upgrades:1,prestige:0,overdrive:23},rule,purchase).eligible,true);
assert.equal(checkUpgrade({level:110,xp:0,upgrades:10,prestige:0,overdrive:0},rule,purchase).eligible,false);
assert.equal(checkUpgrade({level:110,xp:0,upgrades:10,prestige:1,overdrive:0},rule,purchase).eligible,true,'prestige unlocks 11th tier');
assert(!checkUpgrade({level:100,xp:0,upgrades:0,prestige:0,overdrive:0},{...rule,enabled:false},purchase).eligible);
const stored=makePolicies(keys,{speed:{enabled:true,targets:[-3,2,Infinity,'oops',100000000]},memory:{enabled:true,targets:[1]}});
assert.deepEqual(stored.speed.targets.slice(0,5),[0,2,0,0,1000000],'corrupt targets clamped');
const backup=configExport({...defaults,slots:17},{speed:{enabled:true,targets:[10,20]},memory:{enabled:false,targets:[1]}},keys);
assert(!backup.includes('password')&&!backup.includes('token'));
const imported=configImport(backup,defaults,keys);
assert.equal(imported.settings.slots,17);
assert.equal(imported.upgrades.speed.enabled,true);
assert.equal(imported.upgrades.speed.targets[1],20);
assert(!imported.upgrades.accuracy.enabled);
assert.throws(()=>configImport('{}',defaults,keys),/Unsupported/);
const untrusted=JSON.parse(backup);untrusted.settings.secret='token';untrusted.settings.liveQueue=true;untrusted.settings.slots='not number';
const safe=configImport(JSON.stringify(untrusted),defaults,keys);
assert.equal(safe.settings.slots,10);
assert(!('secret' in safe.settings));
assert.equal(safe.settings.liveQueue,false);
console.log('PASS: per-skill default OFF, per-number OD thresholds, prestige gear, real-model delegation, backup/import safety');
